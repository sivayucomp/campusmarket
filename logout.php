<?php
// =====================================================
// logout.php : ออกจากระบบ
// =====================================================
require 'config.php';

// 1. ล้างข้อมูลใน session ทั้งหมด
$_SESSION = [];
session_destroy();

// 2. เริ่ม session ใหม่เพื่อใช้ส่งข้อความแจ้งเตือน
session_start();
flash('ออกจากระบบแล้ว แล้วเจอกันใหม่');

// 3. กลับหน้าแรก
header('Location: index.php');
exit;
